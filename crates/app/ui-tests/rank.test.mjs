import fs from 'fs';
const src = fs.readFileSync(new URL('../ui/app.js', import.meta.url), 'utf8').replace(/\r\n/g, '\n');
const pick = (a, b) => src.slice(src.indexOf(a), src.indexOf(b));
const body = pick('const isQuestion', 'async function runSearch');
const info = { packs: [{ path: 'wikipedia_en-simple.zim' }, { path: 'ifixit_en_all.zim' }] };
const rankHits = new Function('info', body + 'return rankHits;')(info);
const titles = (q, lists) => rankHits(q, lists).map(h => h.title);
let bad = 0;
const check = (name, ok) => { console.log((ok ? 'ok   ' : 'FAIL ') + name); if (!ok) bad++; };
const wiki = [{ title: 'Dehydration', url: 'D', all: true }];
const phone = [{ title: 'How to replace your iPhone 5 battery', url: 'B', all: true }];
check('dehydration question hides an unrelated repair guide', !titles('How do I treat dehydration?', [wiki, phone]).includes(phone[0].title));
check('repair question keeps it', titles('How do I replace a phone battery?', [[], phone]).includes(phone[0].title));
check('plain word search keeps it', titles('treat dehydration', [wiki, phone]).includes(phone[0].title));
check('partial matches hidden when a full match exists', !titles('How do I treat dehydration?', [wiki, [{ title: 'Battery care', url: 'C', all: false }]]).includes('Battery care'));
check('a lone partial match still shows', titles('kinshasa zanzibar', [[{ title: 'Kinshasa', url: 'K', all: false }], []])[0] === 'Kinshasa');
const med = [{ title: 'Pterin-4-alpha-carbinolamine dehydratase deficiency', url: 'P', all: true }, { title: 'Management of dehydration', url: 'M', all: true }];
const order = titles('How do I treat dehydration?', [med, []]);
check('titles with the asked words rank above prefix look-alikes', order.indexOf('Management of dehydration') < order.indexOf('Pterin-4-alpha-carbinolamine dehydratase deficiency'));
process.exit(bad ? 1 : 0);
